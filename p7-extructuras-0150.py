# --- 1. Python Conditions (If simple) ---
print("=== 1. Sentencia IF ===")
a = 33
b = 200
if b > a:
    print("b is greater than a")

print("\n" + "="*40 + "\n")

# --- 2. Python If...Elif ---
print("=== 2. Sentencia IF...ELIF ===")
a = 33
b = 33
if b > a:
    print("b is greater than a")
elif a == b:
    print("a and b are equal")

print("\n" + "="*40 + "\n")

# --- 3. Python If...Else ---
print("=== 3. Sentencia IF...ELSE ===")
a = 200
b = 33
if b > a:
    print("b is greater than a")
else:
    print("b is not greater than a")

print("\n" + "="*40 + "\n")

# --- 4. Python For Loops ---
print("=== 4. Bucle FOR ===")
fruits = ["apple", "banana", "cherry"]
for x in fruits:
    print(x)

print("\n" + "="*40 + "\n")

# --- 5. Python While Loops ---
print("=== 5. Bucle WHILE ===")
i = 1
while i < 6:
    print(i)
    i += 1

